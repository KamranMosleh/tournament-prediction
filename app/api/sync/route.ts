import { NextRequest, NextResponse } from 'next/server'
import { createServiceClient } from '@/lib/supabase/server'
import { getCurrentUser } from '@/lib/auth'
import {
  autoGeneratePunditSummariesForTournament,
  autoGenerateDailyPunditSummariesForTournament,
  autoGenerateMatchRecapsForTournament,
  enrichOpenMatchesForTournament,
} from '@/lib/ai-jobs'
import type { MatchStage, MatchStatus } from '@/types'

const FD_BASE = 'https://api.football-data.org/v4'

type ExistingApiMatch = {
  external_match_id: number | null
  home_team: string
  away_team: string
}

function mapStage(stage: string, group: string | null): { stage: MatchStage; group_name: string | null } {
  const s = stage.toUpperCase()
  if (s.includes('GROUP')) return { stage: 'group', group_name: group?.replace('GROUP_', '') ?? null }
  if (s.includes('ROUND_OF_16') || s.includes('LAST_16')) return { stage: 'round_of_16', group_name: null }
  if (s.includes('QUARTER')) return { stage: 'quarter_final', group_name: null }
  if (s.includes('SEMI')) return { stage: 'semi_final', group_name: null }
  if (s.includes('THIRD')) return { stage: 'third_place', group_name: null }
  if (s.includes('FINAL')) return { stage: 'final', group_name: null }
  return { stage: 'group', group_name: group ?? null }
}

function mapStatus(status: string): MatchStatus {
  const s = status.toUpperCase()
  if (['FINISHED', 'AWARDED'].includes(s)) return 'finished'
  if (['IN_PLAY', 'PAUSED', 'HALFTIME', 'EXTRA_TIME', 'PENALTY'].includes(s)) return 'locked'
  return 'open'
}

async function isAuthorized(req: NextRequest, supabase: ReturnType<typeof createServiceClient>, leagueId?: string): Promise<boolean> {
  const syncSecret = process.env.SYNC_SECRET
  const xSecret = req.headers.get('x-sync-secret') ?? ''

  if (!syncSecret && process.env.NODE_ENV !== 'production') return true
  if (syncSecret && xSecret === syncSecret) return true

  const user = await getCurrentUser()
  if (user) {
    let query = supabase
      .from('players')
      .select('is_admin, league_id')
      .eq('user_id', user.id)
      .eq('is_admin', true)

    if (leagueId) query = query.eq('league_id', leagueId)

    const { data: player } = await query.maybeSingle()
    if (player?.is_admin) return true
  }

  return false
}

export async function POST(req: NextRequest) {
  const supabase = createServiceClient()
  const body = await req.json().catch(() => ({}))
  const leagueId: string | undefined = body.league_id

  if (!(await isAuthorized(req, supabase, leagueId)))
    return NextResponse.json({ error: 'Unauthorized' }, { status: 401 })

  const tournamentCode: string = body.tournament_code ?? 'WC'
  const season: number = body.season ?? new Date().getFullYear()

  if (leagueId) {
    const { data: league } = await supabase
      .from('leagues')
      .select('archived_at')
      .eq('id', leagueId)
      .maybeSingle()

    if (!league) {
      return NextResponse.json({ error: 'League not found' }, { status: 404 })
    }
    if (league.archived_at) {
      return NextResponse.json({ error: 'This league is archived and read-only' }, { status: 409 })
    }
  } else {
    const { data: activeLeague } = await supabase
      .from('leagues')
      .select('id')
      .eq('tournament_code', tournamentCode)
      .eq('tournament_season', season)
      .eq('sync_source', 'api')
      .is('archived_at', null)
      .limit(1)
      .maybeSingle()

    if (!activeLeague) {
      return NextResponse.json({
        ok: true,
        skipped: true,
        reason: 'No active API-sync leagues for this tournament',
      })
    }
  }

  const key = process.env.FOOTBALL_DATA_API_KEY
  if (!key)
    return NextResponse.json({ error: 'FOOTBALL_DATA_API_KEY not configured' }, { status: 500 })

  const start = Date.now()
  let matchesUpdated = 0, matchesLocked = 0, matchesFinished = 0

  try {
    const res = await fetch(`${FD_BASE}/competitions/${tournamentCode}/matches?season=${season}`, {
      headers: { 'X-Auth-Token': key },
    })
    if (!res.ok) throw new Error(`football-data.org ${res.status}`)
    const data = await res.json()
    const incomingMatchIds = ((data.matches ?? []) as Array<{ id?: unknown }>)
      .map(match => typeof match.id === 'number' ? match.id : null)
      .filter((id): id is number => id !== null)
    const existingByExternalId = new Map<number, ExistingApiMatch>()

    if (incomingMatchIds.length > 0) {
      const { data: existingMatches } = await supabase
        .from('matches')
        .select('external_match_id, home_team, away_team')
        .in('external_match_id', incomingMatchIds)

      for (const existing of (existingMatches ?? []) as ExistingApiMatch[]) {
        if (existing.external_match_id !== null) {
          existingByExternalId.set(existing.external_match_id, existing)
        }
      }
    }

    for (const m of data.matches ?? []) {
      const { stage, group_name } = mapStage(m.stage ?? '', m.group ?? null)
      const status = mapStatus(m.status ?? '')
      const isFinished = status === 'finished'
      const homeTeam = m.homeTeam?.shortName ?? m.homeTeam?.name ?? 'TBD'
      const awayTeam = m.awayTeam?.shortName ?? m.awayTeam?.name ?? 'TBD'
      const homeScore = isFinished ? (m.score?.fullTime?.home ?? null) : null
      const awayScore = isFinished ? (m.score?.fullTime?.away ?? null) : null
      const apiWinner = m.score?.winner
      const resultWinnerTeam = stage === 'final' && isFinished
        ? apiWinner === 'HOME_TEAM'
          ? homeTeam
          : apiWinner === 'AWAY_TEAM'
            ? awayTeam
            : homeScore !== null && awayScore !== null && homeScore !== awayScore
              ? homeScore > awayScore ? homeTeam : awayTeam
              : null
        : null

      const existingMatch = typeof m.id === 'number' ? existingByExternalId.get(m.id) : undefined
      const matchupChanged = !!existingMatch && (
        existingMatch.home_team !== homeTeam ||
        existingMatch.away_team !== awayTeam
      )
      const matchPayload = {
        tournament_code: tournamentCode,
        tournament_season: season,
        external_match_id: m.id,
        stage,
        group_name,
        home_team: homeTeam,
        away_team: awayTeam,
        kickoff_time: m.utcDate,
        status,
        home_score: homeScore,
        away_score: awayScore,
        result_winner_team: resultWinnerTeam,
        match_day: m.matchday ?? null,
        venue: m.venue ?? null,
        last_synced_at: new Date().toISOString(),
      }
      const upsertPayload = matchupChanged
        ? { ...matchPayload, ai_insight: null, ai_insight_generated_at: null }
        : matchPayload

      const { error } = await supabase.from('matches').upsert(upsertPayload, { onConflict: 'external_match_id' })

      if (!error) {
        matchesUpdated++
        if (status === 'locked') matchesLocked++
        if (status === 'finished') matchesFinished++
      }
    }

    await supabase.from('sync_log').insert({
      tournament_code: tournamentCode,
      tournament_season: season,
      matches_updated: matchesUpdated,
      matches_locked: matchesLocked,
      matches_finished: matchesFinished,
      duration_ms: Date.now() - start,
    })

    // Auto-generate cached AI content after authoritative match writes.
    const [aiSummaries, aiDailySummaries, aiRecaps, aiEnrichment] = await Promise.all([
      autoGeneratePunditSummariesForTournament(tournamentCode, season, supabase),
      autoGenerateDailyPunditSummariesForTournament(tournamentCode, season, undefined, supabase),
      autoGenerateMatchRecapsForTournament(tournamentCode, season, supabase),
      enrichOpenMatchesForTournament(tournamentCode, season, {}, supabase),
    ])

    return NextResponse.json({ ok: true, matchesUpdated, matchesLocked, matchesFinished, aiSummaries, aiDailySummaries, aiRecaps, aiEnrichment })
  } catch (e: unknown) {
    const msg = e instanceof Error ? e.message : 'Unknown error'
    try {
      await supabase.from('sync_log').insert({
        tournament_code: tournamentCode,
        tournament_season: season,
        error: msg,
        duration_ms: Date.now() - start,
      })
    } catch { /* ignore log failure */ }
    return NextResponse.json({ error: msg }, { status: 500 })
  }
}

export async function GET() {
  const user = await getCurrentUser()
  if (!user) return NextResponse.json({ error: 'Unauthorized' }, { status: 401 })

  const supabase = createServiceClient()
  const { data } = await supabase.from('sync_log').select('*').order('synced_at', { ascending: false }).limit(10)
  return NextResponse.json({ recent: data ?? [] })
}
